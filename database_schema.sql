-- MASTER DATABASE SCHEMA
-- ============================================================================
-- Este arquivo consolida todas as tabelas, relações e funções do sistema.
-- Ele incorpora as melhorias de normalização, reduzindo os +20 scripts antigos 
-- para este único arquivo centralizado.
